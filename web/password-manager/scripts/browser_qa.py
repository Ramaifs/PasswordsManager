def process(seconds=0.1):
    loop = QEventLoop()
    QTimer.singleShot(int(seconds * 1000), loop.quit)
    loop.exec()

def js(expression):
    box = []
    loop = QEventLoop()
    def complete(value):
        box.append(value)
        loop.quit()
    page.runJavaScript(expression, complete)
    QTimer.singleShot(5000, loop.quit)
    loop.exec()
    if not box:
        raise RuntimeError("QA DOM evaluation timeout")
    return box[0]

def wait(expression, seconds=15):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if js(expression): return
        process(.08)
    raise AssertionError("Expected UI condition not reached: " + expression)

def click(selector):
    assert js(f"Boolean(document.querySelector({json.dumps(selector)}))"), selector
    js(f"document.querySelector({json.dumps(selector)}).click()")
    process(.1)

